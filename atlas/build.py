#!/usr/bin/env python3
"""Build the PreciseRx Codebase Atlas and its section index.

Concatenates src/*.html in filename order into dist/preciserx-atlas.html,
fills the data placeholders, runs the content checks, and regenerates INDEX.md.
Exits non-zero if any check fails, so a broken page is never published.
"""
import html
import re
import sys
from collections import Counter
from pathlib import Path

ATLAS_URL = "https://claude.ai/artifact/NDxuSDmUDz114P8W9j6pht"
ROOT = Path(__file__).resolve().parent
SRC, DATA, DIST = ROOT / "src", ROOT / "data", ROOT / "dist"
OUT = DIST / "preciserx-atlas.html"

PILL = {"GET": "get", "POST": "post", "PUT": "put", "PATCH": "patch", "DELETE": "del"}

# Content rules from README.md, enforced so they cannot drift.
BANNED_PHRASES = [
    r"\bexplorers?\b(?<!Internet Explorer)", r"\bre-read\b", r"read from source", r"this atlas",
    r"how to read", r"unless marked", r"spot-checked", r"nothing was (built|run|installed|executed)",
    r"verified in source", r"while writing", r"generated (by|with)", r"class=\"pill [vri]\"",
]
SECRET_PATTERNS = {
    "AWS account id": r"(?<![\d.,])\d{12}(?![\d.])",
    "AWS access key": r"\bAKIA[0-9A-Z]{16}\b",
    "ARN": r"arn:aws:[a-z0-9-]+:",
    "private key": r"BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY",
    "email address": r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]{2,}",
    "UUID-shaped secret": r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b",
}
BALANCED_TAGS = ["section", "table", "div", "ul", "ol", "figure", "svg", "pre", "dl", "details", "p", "li", "tr", "td"]


def contract_rows():
    rows = []
    for line in (DATA / "contract.tsv").read_text().splitlines():
        if not line.strip():
            continue
        f, fn, method, svc, path, note = (line.split("\t") + [""] * 6)[:6]
        cls = PILL.get(method.split()[0], "get")
        label = "DEL" if method == "DELETE" else method
        rows.append(
            f'      <tr><td><span class="pill {cls}">{html.escape(label)}</span></td>'
            f'<td class="nw">{html.escape(svc)}</td><td><code>{html.escape(path)}</code></td>'
            f'<td class="path">{html.escape(f)} · {html.escape(fn)}</td><td>{html.escape(note)}</td></tr>'
        )
    return rows


def assemble():
    rows = contract_rows()
    page = "".join(p.read_text() for p in sorted(SRC.glob("*.html")))
    return (
        page.replace("{{POLY}}", (DATA / "poly.txt").read_text().strip())
        .replace("{{AREA}}", (DATA / "area.txt").read_text().strip())
        .replace("{{CONTRACT_ROWS}}", "\n".join(rows))
        .replace("{{CONTRACT_COUNT}}", str(len(rows)))
    )


def text_only(fragment):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", fragment))).strip()


def check(page):
    problems = []
    if leftover := re.findall(r"\{\{[A-Z_]+\}\}", page):
        problems.append(f"unfilled placeholders: {sorted(set(leftover))}")
    ids = re.findall(r'\sid="([^"]+)"', page)
    if dups := [i for i, n in Counter(ids).items() if n > 1]:
        problems.append(f"duplicate ids: {dups}")
    if missing := sorted(h for h in set(re.findall(r'href="#([^"]+)"', page)) if h not in set(ids)):
        problems.append(f"links to missing anchors: {missing}")
    for tag in BALANCED_TAGS:
        opened, closed = len(re.findall(rf"<{tag}[\s>]", page)), len(re.findall(rf"</{tag}>", page))
        if opened != closed:
            problems.append(f"unbalanced <{tag}>: {opened} opened, {closed} closed")
    for n, block in enumerate(re.findall(r'<pre class="mermaid">(.*?)</pre>', page, re.S), 1):
        if bad := [l.strip() for l in block.splitlines() if re.search(r"[;#<&]", l)]:
            problems.append(f"mermaid block {n} has ; # < or &: {bad[:2]}")
    body = text_only(re.sub(r"<(style|script)\b.*?</\1>", "", page, flags=re.S))
    for rx in BANNED_PHRASES:
        target = page if rx.startswith("class=") else body.replace("Internet Explorer", "")
        if m := re.search(rx, target, re.I):
            problems.append(f"generation note or provenance mark: {m.group(0)!r}")
    for name, rx in SECRET_PATTERNS.items():
        if m := re.search(rx, body):
            problems.append(f"possible {name}: {m.group(0)!r}")
    if len(page.encode()) > 16 * 1024 * 1024:
        problems.append("page exceeds 16 MB")
    return problems


def write_index(page):
    lines = [
        "# Atlas section index",
        "",
        f"Sections of the [PreciseRx Codebase Atlas]({ATLAS_URL}). Generated by `atlas/build.py`; do not edit by hand.",
        f"To point the user to a section, give them `{ATLAS_URL}#<anchor>`. Do not read the atlas itself for your own work.",
    ]
    group = None
    for sec in re.finditer(r'<section class="doc" id="([^"]+)" data-group="([^"]+)" data-title="([^"]+)">(.*?)</section>', page, re.S):
        sid, grp, title, body = sec.groups()
        if grp != group:
            lines += ["", f"## {html.unescape(grp)}", ""]
            group = grp
        summary = re.search(r'<p class="summary">(.*?)</p>', body, re.S)
        blurb = text_only(summary.group(1)) if summary else ""
        blurb = blurb if len(blurb) <= 180 else blurb[:177].rsplit(" ", 1)[0] + "…"
        lines.append(f"- `#{sid}` **{html.unescape(title)}**: {blurb}")
        subs = [f"`#{i}` {text_only(t)}" for i, t in re.findall(r'<h3 id="([^"]+)">(.*?)</h3>', body, re.S)]
        if subs:
            lines.append("  - " + " · ".join(subs))
    (ROOT / "INDEX.md").write_text("\n".join(lines).strip() + "\n")


def main():
    page = assemble()
    problems = check(page)
    if problems:
        print("Build refused:", *problems, sep="\n  - ")
        sys.exit(1)
    DIST.mkdir(exist_ok=True)
    OUT.write_text(page)
    write_index(page)
    sections = len(re.findall(r'<section class="doc"', page))
    print(f"Built {OUT.relative_to(ROOT.parent)} ({len(page.encode()):,} bytes, {sections} sections) and INDEX.md")


if __name__ == "__main__":
    main()
